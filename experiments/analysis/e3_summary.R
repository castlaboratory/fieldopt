# E3 summary: bias and coverage of the variance estimators of design_variance()
#
# Usage:  Rscript experiments/analysis/e3_summary.R [out_dir]
suppressPackageStartupMessages({
  library(dplyr)
  library(tidyr)
  library(ggplot2)
  library(knitr)
})
args <- commandArgs(trailingOnly = TRUE)
out_dir <- if (length(args) >= 1) args[1] else "experiments/out/e3"
fig_dir <- "experiments/figures"
res <- readRDS(file.path(out_dir, "e3_results.rds"))
st <- res$settings
session <- readLines(file.path(out_dir, "session.txt"))
range_levels <- c("iid", "short", "medium", "long")
design_levels <- c("srs", "lpm", "systematic", "systematic_r4")

per_var <- res$est |>
  left_join(res$truth, by = c("frame", "y")) |>
  mutate(range = factor(sub("^y_([a-z]+)_[0-9]+$", "\\1", y), range_levels),
         design = factor(design, design_levels)) |>
  group_by(frame, design, n, range, y) |>
  summarise(
    method = first(method),
    true_var = var(total),
    mean_est = mean(variance),
    coverage_normal = mean(abs(total - true_total) <= qnorm(0.975) * sqrt(variance)),
    coverage = mean(abs(total - true_total) <= qt(0.975, df) * sqrt(variance)),
    .groups = "drop"
  ) |>
  mutate(rel_bias = mean_est / true_var - 1)

tab <- per_var |>
  group_by(design, method, range, n) |>
  summarise(rel_bias = mean(rel_bias), coverage = mean(coverage), .groups = "drop") |>
  pivot_wider(names_from = n, values_from = c(rel_bias, coverage), names_glue = "{.value} (n = {n})") |>
  arrange(design, range)
by_frame <- per_var |>
  group_by(frame, design, range) |>
  summarise(rel_bias = mean(rel_bias), .groups = "drop") |>
  pivot_wider(names_from = design, values_from = rel_bias) |>
  arrange(frame, range)

theme_set(theme_minimal(base_size = 10))
p <- per_var |>
  group_by(design, range, n, frame) |>
  summarise(rel_bias = mean(rel_bias), .groups = "drop") |>
  ggplot(aes(range, rel_bias, colour = design, shape = frame)) +
  geom_hline(yintercept = 0, colour = "grey50") +
  geom_point(position = position_dodge(width = 0.6)) +
  facet_wrap(~n, labeller = label_both) +
  scale_y_continuous(labels = scales::percent) +
  labs(x = "spatial range of the study variable", y = "relative bias of the variance estimator")
ggsave(file.path(fig_dir, "e3-bias.png"), p, width = 6.5, height = 3.2, dpi = 110)

fmt <- function(d) {
  d |> mutate(across(starts_with("rel_bias"), \(x) sprintf("%+.0f%%", 100 * x)),
              across(starts_with("coverage"), \(x) sprintf("%.3f", x)))
}
tbl <- function(d) paste(kable(d, format = "pipe"), collapse = "\n")
report <- c(
  "# E3 — bias and coverage of the variance estimators",
  "",
  paste0("Generated by `experiments/analysis/e3_summary.R` from `", out_dir, "` (", tail(session, 1), ")."),
  "",
  "## Question",
  "",
  "E1 compared designs by their true variance. In a survey only the estimate is available, so the",
  "comparison is usable only if `design_variance()` estimates the variance well under each design.",
  "",
  "## Design",
  "",
  "- Frames F1 (real 448-cell grid), F2 (uniform grid), F3 (clustered) of E1/E2.",
  "- Designs: srs (simple random sampling formula), lpm (local-mean estimator of Grafström and Schelin),",
  "  systematic along a Hilbert curve in one replicate (local-mean estimator, the customary approximation)",
  "  and in four interpenetrating replicates (between-replicate estimator, 3 degrees of freedom).",
  paste0("- n in {", paste(st$N_VAR, collapse = ", "), "}; ", st$R_SAMPLES, " samples per (frame, design, n); ",
         st$FIELDS_PER_RANGE, " fields of E1 per spatial range (iid, short, medium, long)."),
  "- Relative bias = mean of the variance estimates / empirical variance of the HT totals - 1; coverage of",
  "  the 95% interval with the t quantile on the `df` that `design_variance()` reports (3 for four",
  "  replicates; n - 1 otherwise, practically normal).",
  "",
  "## Results",
  "",
  "Mean over frames and fields:",
  "",
  tbl(fmt(tab)),
  "",
  "Relative bias by frame (mean over n):",
  "",
  tbl(by_frame |> mutate(across(all_of(design_levels), \(x) sprintf("%+.0f%%", 100 * x)))),
  "",
  "![Bias of the variance estimators](figures/e3-bias.png)",
  "",
  "## What this means",
  "",
  "1. **srs and replicates are unbiased** in every scenario. With four replicates the variance has 3",
  paste0("   degrees of freedom: the normal interval covers only ",
         sprintf("%.2f", mean(per_var$coverage_normal[per_var$design == "systematic_r4"])),
         ", the t interval ", sprintf("%.2f", mean(per_var$coverage[per_var$design == "systematic_r4"])), "."),
  "2. **The local-mean estimator is conservative when the variable is spatially smooth** and close to",
  "   unbiased when it is not, as expected from its construction (the local mean removes only the trend",
  "   inside each neighbourhood). Under lpm the overestimate at medium and long range is about a third;",
  "   intervals over-cover (0.96 to 0.98). A comparison of designs by their *estimated* variance is",
  "   therefore biased against lpm and single-replicate systematic samples by roughly that much; E1 used",
  "   the true variance and is not affected.",
  "3. **Before the fix of fieldopt-core 0.10.0** the neighbourhood grew until the inclusion probabilities",
  "   summed to one (about N/n units) and the overestimate reached +60 to +160% on smooth fields",
  "   (`experiments/out/e3_before_fix`). The estimator now matches `BalancedSampling::vsb()` with k = 3.",
  "4. For single-replicate systematic samples no design-unbiased estimator exists; the local-mean",
  "   approximation is conservative here by 12 to 68%. Interpenetrating replicates cost nothing in",
  "   travel and give an unbiased estimate: they are the recommended default for systematic designs."
)
writeLines(report, "experiments/e3_variance_estimators.md")
saveRDS(list(per_var = per_var, table = tab, by_frame = by_frame), file.path(out_dir, "e3_tables.rds"))
message("report written")
